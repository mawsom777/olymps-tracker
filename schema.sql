CREATE DATABASE IF NOT EXISTS olymp_tracker CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE olymp_tracker;

CREATE TABLE IF NOT EXISTS olympiads (
  id             INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name           VARCHAR(255) NOT NULL,                 -- «Олимпиада (Профиль)»
  reg_start      DATETIME NULL DEFAULT NULL,            -- NULL = «Уточняется на сайте»
  reg_end        DATETIME NULL DEFAULT NULL,            -- время 23:59:00 => время не указано
  stage1_date    DATETIME NULL DEFAULT NULL,
  stage1_format  VARCHAR(64)  NOT NULL DEFAULT '',
  final_date     DATETIME NULL DEFAULT NULL,
  final_format   VARCHAR(64)  NOT NULL DEFAULT '',
  stages_count   TINYINT UNSIGNED NOT NULL DEFAULT 2,
  lvl            TINYINT UNSIGNED NOT NULL DEFAULT 1,
  registered     TINYINT(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  KEY idx_end (reg_end)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

